"""Write engine/comfyui/extra_model_paths.yaml pointing ComfyUI at ./models.

Called by setup.bat so the engine (which is gitignored and cloned fresh) knows
where the project's downloaded weights live. Uses an absolute path derived from
this repo's location, so it works wherever the project is checked out.
"""
from __future__ import annotations

from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MODELS = (ROOT / "models").as_posix()
TARGET = ROOT / "engine" / "comfyui" / "extra_model_paths.yaml"

CONTENT = f"""# Auto-generated by scripts/write_model_paths.py — points ComfyUI at ./models
vizgen:
    base_path: {MODELS}/
    is_default: true
    checkpoints: checkpoints/
    configs: configs/
    loras: loras/
    vae: vae/
    text_encoders: |
         text_encoders/
         clip/
    diffusion_models: |
         unet/
         diffusion_models/
    clip_vision: clip_vision/
    embeddings: embeddings/
    controlnet: controlnet/
    upscale_models: upscale_models/
    hypernetworks: hypernetworks/
"""


def main() -> None:
    TARGET.parent.mkdir(parents=True, exist_ok=True)
    TARGET.write_text(CONTENT, encoding="utf-8")
    print(f"Wrote {TARGET} -> base_path {MODELS}/")


if __name__ == "__main__":
    main()
